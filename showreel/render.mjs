// Renders showreel/index.html frame-by-frame to showreel.mp4 (1920x1080, 30fps, with a synthesized beat).
// Usage: node showreel/render.mjs [fps]   (needs playwright + ffmpeg)
import { spawn } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';
import { createRequire } from 'node:module';

// require() so a globally installed playwright works via NODE_PATH
const { chromium } = createRequire(import.meta.url)('playwright');

const dir = path.dirname(fileURLToPath(import.meta.url));
const fps = Number(process.argv[2] || 30);
const out = path.join(dir, 'showreel.mp4');

const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
await page.goto(pathToFileURL(path.join(dir, 'index.html')).href + '?capture');
const duration = await page.evaluate(() => window.SHOWREEL_DURATION);
const frames = Math.round(duration * fps);

// 120 BPM kick + offbeat hat, generated by ffmpeg so the beat lines up with the visuals.
const kick = 'sin(2*PI*(45*t+(110/30)*(1-exp(-30*mod(t,0.5)))))*exp(-7*mod(t,0.5))';
const hat = '0.12*(random(0)*2-1)*exp(-40*mod(t+0.25,0.5))';
const ff = spawn('ffmpeg', ['-y', '-f', 'image2pipe', '-framerate', String(fps), '-i', '-',
  '-f', 'lavfi', '-i', `aevalsrc='0.6*${kick}+${hat}':s=48000:d=${duration}`,
  '-af', `afade=t=out:st=${duration - 1}:d=1`,
  '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-crf', '18', '-preset', 'medium',
  '-c:a', 'aac', '-b:a', '160k', '-shortest', '-movflags', '+faststart', out],
  { stdio: ['pipe', 'inherit', 'inherit'] });

const canvas = page.locator('canvas');
for (let i = 0; i < frames; i++) {
  await page.evaluate(t => window.renderFrame(t), i / fps);
  const png = await canvas.screenshot({ type: 'png' });
  if (!ff.stdin.write(png)) await new Promise(r => ff.stdin.once('drain', r));
  if (i % fps === 0) process.stdout.write(`\rframe ${i}/${frames}`);
}
ff.stdin.end();
await new Promise(r => ff.on('close', r));
await browser.close();
console.log(`\nwrote ${out}`);
